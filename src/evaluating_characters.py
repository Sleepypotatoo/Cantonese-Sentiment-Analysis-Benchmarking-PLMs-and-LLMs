import os
import pandas as pd
import re
from sklearn.metrics import precision_recall_fscore_support

# 特征库（保持你之前的定义，此处省略展示，请保留你已修改好的 FEATURE_LIB）

from sklearn.metrics import classification_report, accuracy_score

def analyze_feature_impact(error_file, pred_file=None, output_dir="feature_analysis_results"):
    os.makedirs(output_dir, exist_ok=True)

    # ---------- 1. 读取错误样本 ----------
    df_err = pd.read_csv(error_file, encoding='utf_8_sig')
    total_errors = len(df_err)
    df_err['error_path'] = df_err.apply(lambda x: f"{x['true_rating']} -> {x['pred_rating']}", axis=1)

    # ---------- 2. 定义特征匹配函数 ----------
    def get_hits(text):
        hits = []
        for cat, patterns in FEATURE_LIB.items():
            regex = "|".join([p if p.startswith('.') or '\\' in p else re.escape(p) for p in patterns])
            if re.search(regex, text):
                hits.append(cat)
        return hits

    df_err['hit_categories'] = df_err['text'].apply(get_hits)

    # 准备存储详细分类报告的文本
    report_lines = []

    # ---------- 3. 若提供预测文件，读取并计算详细指标 ----------
    if pred_file is not None:
        df_pred = pd.read_csv(pred_file, encoding='utf_8_sig')
        df_pred['hit_categories'] = df_pred['text'].apply(get_hits)
        print(f"全量预测样本数: {len(df_pred)}")
        global_acc = accuracy_score(df_pred['true_rating'], df_pred['pred_rating'])
        report_lines.append(f"总体测试集准确率: {global_acc:.4f}\n")
        report_lines.append("="*80 + "\n")

    # ---------- 4. 逐特征统计 ----------
    results = []  # 用于汇总表
    for category in FEATURE_LIB.keys():
        err_subset = df_err[df_err['hit_categories'].apply(lambda x: category in x)]
        err_count = len(err_subset)
        mode_path = err_subset['error_path'].mode()[0] if err_count > 0 else "N/A"
        row = {
            "特征类别": category,
            "错误样本数": err_count,
            # "典型错误路径": mode_path
        }

        if pred_file is not None:
            pred_subset = df_pred[df_pred['hit_categories'].apply(lambda x: category in x)]
            if len(pred_subset) > 0:
                # 使用 weighted 平均，得到总体的 precision, recall, f1
                p, r, f1, _ = precision_recall_fscore_support(
                    pred_subset['true_rating'],
                    pred_subset['pred_rating'],
                    average='macro',
                    zero_division=0
                )
                row["子集样本数"] = len(pred_subset)
                row["Precision"] = round(p, 4)
                row["Recall"] = round(r, 4)
                row["F1-score"] = round(f1, 4)
            else:
                row["子集样本数"] = 0
                row["Precision"] = row["Recall"] = row["F1-score"] = None

        results.append(row)

    # 保存详细分类报告到文本文件
    if pred_file is not None:
        report_path = os.path.join(output_dir, "classification_reports.txt")
        with open(report_path, 'w', encoding='utf-8') as f:
            f.writelines(report_lines)
        print(f"各特征子集分类报告已保存至: {report_path}")

    # 保存汇总表（包含各类别 F1）
    report_df = pd.DataFrame(results).sort_values(by="错误样本数", ascending=False)
    stat_path = os.path.join(output_dir, "feature_statistics.csv")
    report_df.to_csv(stat_path, index=False, encoding='utf_8_sig')
    print(f"\n统计报告已保存至: {stat_path}")

    # 打印汇总表（控制台）
    print("\n" + "=" * 70)
    print("各语言特征对模型错误的影响分析（汇总）")
    print("=" * 70)
    print(report_df.to_string(index=False))

    # 保存各特征命中的错误样本
    for category in FEATURE_LIB.keys():
        err_subset = df_err[df_err['hit_categories'].apply(lambda x: category in x)]
        if len(err_subset) > 0:
            safe_name = category.replace(":", "_").replace("/", "_")
            err_subset.to_csv(os.path.join(output_dir, f"errors_{safe_name}.csv"),
                              index=False, encoding='utf_8_sig')

    return report_df


